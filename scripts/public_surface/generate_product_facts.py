#!/usr/bin/env python3
"""Generate data/public-product-facts.json, the public claims contract.

Every number the README, site, manifests and docs publish is read from here.
Each value is derived from the package or the repository, never typed:

    version, python_min, license   pyproject.toml
    engines, gates, modes,
    research_sources, tiers        ARCHITECTURE_INVARIANTS.json (itself generated)
    import_cycles                  import_graph.build_graph('.')
    critical_antipatterns          antipattern_detector.detect_all('.')
    architecture_score             architecture_scorer.score_project('.')
    tests                          pytest --collect-only

    python scripts/public_surface/generate_product_facts.py            # print
    python scripts/public_surface/generate_product_facts.py --write    # regenerate
    python scripts/public_surface/generate_product_facts.py --check    # exit 1 if stale
"""

from __future__ import annotations

import argparse
import json
import pathlib
import re
import subprocess
import sys
import tomllib

REPO = pathlib.Path(__file__).resolve().parents[2]
OUTPUT = REPO / "data" / "public-product-facts.json"

CANONICAL_REPO = "https://github.com/maioio/genesis-architect"
CANONICAL_SITE = "https://maioio.github.io/genesis-architect/"

PROVENANCE = {
    "version": "pyproject.toml [project].version",
    "python_min": "pyproject.toml [project].requires-python",
    "license": "pyproject.toml [project].license",
    "engines": "ARCHITECTURE_INVARIANTS.json counts.engines",
    "gates": "ARCHITECTURE_INVARIANTS.json counts.gates",
    "modes": "ARCHITECTURE_INVARIANTS.json counts.modes",
    "research_sources": "ARCHITECTURE_INVARIANTS.json counts.research_sources",
    "research_tiers": "ARCHITECTURE_INVARIANTS.json counts.research_tiers",
    "import_cycles": "import_graph.build_graph('.')['cycle_count']",
    "critical_antipatterns": "antipattern_detector.detect_all('.').critical_count",
    "architecture_score": "architecture_scorer.score_project('.')['total']",
    "tests": "pytest --collect-only -q",
}


def _tests_collected() -> int:
    proc = subprocess.run(
        [sys.executable, "-m", "pytest", "--collect-only", "-q"],
        cwd=REPO, capture_output=True, text=True, check=False)
    match = re.search(r"(\d+) tests? collected", proc.stdout)
    if not match:
        raise SystemExit("could not read the collected test count from pytest")
    return int(match.group(1))


def collect() -> dict:
    sys.path.insert(0, str(REPO / "src"))
    from genesis_architect.core.antipattern_detector import detect_all
    from genesis_architect.core.architecture_scorer import score_project
    from genesis_architect.core.import_graph import build_graph

    project = tomllib.loads((REPO / "pyproject.toml").read_text(encoding="utf-8"))["project"]
    invariants = json.loads((REPO / "ARCHITECTURE_INVARIANTS.json").read_text(encoding="utf-8"))
    counts = invariants["counts"]
    score = score_project(str(REPO))
    if not score.get("scored"):
        raise SystemExit(f"architecture score unavailable: {score.get('unscored_reason')}")

    return {
        "_comment": "Generated by scripts/public_surface/generate_product_facts.py. "
                    "Do not edit by hand. Public prose that disagrees with this file is wrong.",
        "version": project["version"],
        "python_min": project["requires-python"].lstrip(">="),
        "license": project["license"],
        "repository": CANONICAL_REPO,
        "website": CANONICAL_SITE,
        "engines": counts["engines"],
        "gates": counts["gates"],
        "modes": counts["modes"],
        "research_sources": counts["research_sources"],
        "research_tiers": counts["research_tiers"],
        "import_cycles": build_graph(str(REPO))["cycle_count"],
        "critical_antipatterns": detect_all(str(REPO)).critical_count,
        "architecture_score": score["total"],
        "tests": _tests_collected(),
        "provenance": PROVENANCE,
    }


def render(facts: dict) -> str:
    return json.dumps(facts, indent=2, ensure_ascii=False) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--write", action="store_true", help="regenerate the file")
    ap.add_argument("--check", action="store_true", help="exit 1 if the file is stale")
    args = ap.parse_args()

    text = render(collect())
    if args.write:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {OUTPUT.relative_to(REPO)}")
        return 0
    if args.check:
        if not OUTPUT.exists():
            print(f"MISSING: {OUTPUT.name}; run with --write", file=sys.stderr)
            return 1
        if OUTPUT.read_text(encoding="utf-8") != text:
            print(f"STALE: {OUTPUT.name} disagrees with the code.\n"
                  "       Regenerate: python scripts/public_surface/generate_product_facts.py --write",
                  file=sys.stderr)
            return 1
        print(f"{OUTPUT.name} matches the live package")
        return 0
    print(text, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

#!/usr/bin/env python3
"""Generate the public capability catalog from the code.

Chain: src/genesis_architect/pro/capability_map.py (what exists)
     -> capability_catalog.py (family, maturity, effects)
     -> data/public-capabilities.json   (machine-readable)
     -> site/src/content/docs/capabilities.md  (human catalog, generated)

    python scripts/public_surface/generate_capability_catalog.py --write
    python scripts/public_surface/generate_capability_catalog.py --check   # exit 1 if stale
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parents[2]
JSON_OUT = REPO / "data" / "public-capabilities.json"
DOC_OUT = REPO / "site" / "src" / "content" / "docs" / "capabilities.md"

WRITES = {
    "none": "nothing",
    "state": ".genesis/ and reports",
    "project": "files on disk (opt-in or dry run first)",
}
NETWORK = {"none": "offline", "optional": "offline by default", "required": "needs network"}
LLM = {"no": "no", "optional": "optional", "required": "required"}


def _test_files(module: str) -> list[str]:
    hits = []
    for f in sorted((REPO / "tests").glob("test_*.py")):
        if module in f.read_text(encoding="utf-8", errors="ignore"):
            hits.append(f"tests/{f.name}")
    return hits


def collect() -> dict:
    sys.path.insert(0, str(REPO / "src"))
    from genesis_architect.pro import capability_catalog as cat
    from genesis_architect.pro.capability_map import INTERNAL

    rows = cat.build_catalog()
    for r in rows:
        r["test_evidence"] = _test_files(r["id"])
        r["public_status"] = "PUBLIC" if r["command"] else "NO_DOOR"
        r["docs_url"] = "https://maioio.github.io/genesis-architect/capabilities/"
    return {
        "_comment": "Generated by scripts/public_surface/generate_capability_catalog.py. Do not edit by hand.",
        "counts": {
            "capabilities": len(rows),
            "internal_modules": len(INTERNAL),
            "commands": len(cat.COMMANDS),
            "families": len(cat.FAMILIES),
        },
        "families": cat.FAMILIES,
        "capabilities": rows,
        "commands": [c.__dict__ for c in cat.COMMANDS],
    }


def render_json(data: dict) -> str:
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def _cell(text: str | None) -> str:
    return (text or "").replace("|", "\\|")


def render_doc(data: dict) -> str:
    n = data["counts"]
    out = [
        "---",
        "title: Capabilities",
        "description: Every user-facing Genesis capability, grouped by what you want to do, with its maturity, what it writes and what it needs.",
        "---",
        "",
        "{/* Generated by scripts/public_surface/generate_capability_catalog.py. Do not edit by hand. */}",
        "",
        f"Genesis maps **{n['capabilities']} user-facing capabilities** to a command, in {n['families']} families. "
        f"{n['internal_modules']} further modules are internal plumbing with no command of their own.",
        "",
        "This count is different from the number of registered engines on the home page. "
        "Engines are the units the decision engine schedules; capabilities are the things a person can ask for. "
        "Several capabilities run inside one engine, and some engines serve several capabilities.",
        "",
        "## How to read the tables",
        "",
        "| Column | Meaning |",
        "|---|---|",
        "| Maturity | `stable`: default install, covered by tests. `optional`: needs an extra or an external tool. `experimental`: no direct test coverage yet |",
        "| Writes | What it can leave behind. `.genesis/ and reports` stays inside the project's own state folder and generated reports; `files on disk` is always opt-in or a dry run first |",
        "| Needs | Network, LLM and optional dependencies |",
        "",
        "A row with `Writes: nothing` does not change your files. "
        "Commands that write state, such as `recover`, `harden` and `decide`, put it under `.genesis/` and in generated reports. "
        "The machine-readable source is `data/public-capabilities.json`.",
        "",
    ]
    for key, title in data["families"].items():
        rows = [r for r in data["capabilities"] if r["family"] == key]
        out += [
            f"## {title}",
            "",
            "| Capability | What it does | Command | Maturity | Writes | Needs |",
            "|---|---|---|---|---|---|",
        ]
        for r in rows:
            needs = [NETWORK[r["network"]]]
            if r["requires_llm"] != "no":
                needs.append(f"LLM {LLM[r['requires_llm']]}")
            if r["optional_dependency"]:
                needs.append(r["optional_dependency"])
            cmd = f"`{r['command']}`" if r["command"] else "none yet"
            what = _cell(r["summary"]) + (f" _{_cell(r['limitation'])}_" if r["limitation"] else "")
            out.append(
                f"| {_cell(r['name'])} | {what} | {_cell(cmd)} | {r['maturity']} | "
                f"{WRITES[r['writes']]} | {_cell('; '.join(needs))} |"
            )
        out.append("")
    out += ["## Commands", "", "| Command | Status | What it does |", "|---|---|---|"]
    for c in data["commands"]:
        out.append(f"| `genesis {c['name']}` | {c['status']} | {_cell(c['summary'])} |")
    out += [
        "",
        "`PUBLIC` is the everyday surface. `ADVANCED` is supported but narrower. "
        "`LEGACY` is kept so old scripts keep working and adds nothing new.",
        "",
    ]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    data = collect()
    targets = {JSON_OUT: render_json(data), DOC_OUT: render_doc(data)}
    if args.write:
        for path, text in targets.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {path.relative_to(REPO)}")
        return 0
    if args.check:
        bad = [p for p, t in targets.items() if not p.exists() or p.read_text(encoding="utf-8") != t]
        for p in bad:
            print(
                f"STALE: {p.relative_to(REPO)} disagrees with capability_map/capability_catalog.\n"
                "       Regenerate: python scripts/public_surface/generate_capability_catalog.py --write",
                file=sys.stderr,
            )
        if not bad:
            print("capability catalog matches the code")
        return 1 if bad else 0
    print(render_json(data), end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
